//for
for(let i=0; i<=10;i++){
    console.log(`2*${i}=${2*i}`);
}
//sum of 1 to 100
let sum =0;
for(let i=0; i<=100;i++){
    sum+=i;
}
console.log(`Sum of 100 is ${sum}`);

// do while loop
let j =1;
do{
    console.log(`2*${j}=${2*j}`);
    j++;
}while(j<=10)

while(j>0)
{
    console.log(`2*${j}=${2*j}`);
    j--;
}